#!/usr/bin/env bash
# H.13: design pattern -> source line mapping for the Sprint 3 doc.
# Finds every "// MARK: - [Pattern: <Name>] <Role>" anchor in codey/Sources,
# takes the declaration that follows it, and emits a LaTeX longtable with
# the file and line range (anchor+1 .. the declaration's closing brace).
# Each row \ref's the file's Appendix B subsection (labels from
# gen-appendix-b.sh, same sanitising rule).
#
#   scripts/gen-pattern-map.sh [out]   # default docs/source/generated/pattern_lines.tex
#
# Run AFTER the code freeze, together with gen-appendix-b.sh, so the line
# numbers match the Appendix B listings.
set -euo pipefail
cd "$(dirname "$0")/.."

out=${1:-docs/source/generated/pattern_lines.tex}
mkdir -p "$(dirname "$out")"

rows=$(git ls-files 'codey/Sources/*.swift' | while IFS= read -r file; do
    awk -v file="$file" '
        function flush_decl(line,   indent, name) {
            indent = line; sub(/[^ ].*$/, "", indent)
            name = line
            sub(/^ */, "", name)
            ext = (name ~ /^extension /)
            sub(/^(public |private |fileprivate |final |indirect )*(final )?(class|struct|enum|protocol|extension|actor) /, "", name)
            sub(/[:{<( ].*$/, "", name)
            if (ext) name = name " (extension)"
            want_close = indent "}"
            pname = name
            # A declaration that opens and closes on one line ends there.
            if (line ~ /\{.*\}[ ]*$/) { emit(NR); return }
            waiting = 1
        }
        function emit(end) {
            printf "%s\t%s\t%s\t%s\t%d\t%d\n", pattern, role, pname, file, start, end
            waiting = 0; looking = 0
        }
        match($0, /\/\/ MARK: - \[Pattern: [A-Za-z]+\] /) {
            if (looking) next   # stacked anchors share one declaration
            pattern = $0; sub(/.*\[Pattern: /, "", pattern); sub(/\].*/, "", pattern)
            role = $0; sub(/.*\[Pattern: [A-Za-z]+\] /, "", role)
            start = NR + 1; looking = 1
            next
        }
        looking && !waiting {
            s = $0; sub(/^ */, "", s)
            if (s ~ /^\/\/\// || s ~ /^@/ || s == "") next
            flush_decl($0); next
        }
        waiting && $0 == want_close { emit(NR) }
    ' "$file"
    # Stacked anchors: re-run so the second anchor on the same declaration
    # gets a row too (awk above only emits for the first).
    awk -v file="$file" '
        /\/\/ MARK: - \[Pattern: [A-Za-z]+\] / {
            if (first) { p=$0; sub(/.*\[Pattern: /,"",p); sub(/\].*/,"",p); r=$0; sub(/.*\[Pattern: [A-Za-z]+\] /,"",r); print "STACK\t" p "\t" r "\t" file "\t" first }
            else first = NR
            next
        }
        { first = 0 }
    ' "$file"
done)

# Resolve stacked anchors to the row of the anchor right below them.
resolved=$(printf '%s\n' "$rows" | awk -F'\t' '
    $1 != "STACK" { print; key[$4 FS ($5 - 1)] = $0; next }
    { stack[++n] = $0 }
    END {
        for (i = 1; i <= n; i++) {
            split(stack[i], s, "\t")
            # s[5] is the first anchor of the stack, whose row starts at s[5] + 1.
            k = s[4] FS s[5]
            if (k in key) { split(key[k], r, "\t"); print s[2] "\t" s[3] "\t" r[3] "\t" r[4] "\t" r[5] "\t" r[6] }
        }
    }' | sort -t$'\t' -k1,1 -k4,4 -k5,5n)

tex_escape() { sed -e 's/[_&%#$]/\\&/g'; }
label_of() { printf 'appB:%s' "$(printf '%s' "$1" | sed 's/[^A-Za-z0-9]/-/g')"; }

{
    echo "% Generated by scripts/gen-pattern-map.sh on $(git rev-parse --short HEAD). Do not edit."
    echo '\begin{longtable}{@{}p{0.11\linewidth}p{0.22\linewidth}p{0.2\linewidth}p{0.27\linewidth}p{0.1\linewidth}@{}}'
    echo '\caption{Design pattern participants mapped to source lines (Appendix B).}\label{tab:pattern-lines}\\'
    echo '\toprule Pattern & Role & Participant & File (Appendix B) & Lines \\ \midrule \endfirsthead'
    echo '\toprule Pattern & Role & Participant & File (Appendix B) & Lines \\ \midrule \endhead'
    printf '%s\n' "$resolved" | while IFS=$'\t' read -r pattern role name file from to; do
        [[ -z "$pattern" ]] && continue
        short=${file#codey/Sources/}
        printf '%s & %s & \\texttt{%s} & \\texttt{%s} (\\ref{%s}) & %s--%s \\\\\n' \
            "$pattern" "$(tex_escape <<<"$role")" "$(tex_escape <<<"$name")" \
            "$(tex_escape <<<"$short")" "$(label_of "$file")" "$from" "$to"
    done
    echo '\bottomrule'
    echo '\end{longtable}'
} > "$out"

echo "gen-pattern-map: $(grep -cE '[0-9]--[0-9]+ \\\\$' "$out") rows -> $out"
