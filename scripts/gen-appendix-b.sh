#!/usr/bin/env bash
# H.21: Appendix B for the Sprint 3 doc. Every tracked source/config file
# gets its own \subsection (labelled appB:<path>, the label gen-pattern-map.sh
# refers to) and a line-numbered \lstinputlisting.
#
#   scripts/gen-appendix-b.sh [outdir]   # default docs/source/generated
#
# Writes <outdir>/appendix_b.tex (\input it where Appendix B goes) and
# <outdir>/appendix_b_preamble.tex (\input it in the preamble: listings
# languages for Swift/SQL/bash/JSON/YAML). Listing paths are relative to
# docs/source/, where the .tex is built.
#
# Excluded: secrets (Config/Secrets.xcconfig is untracked anyway), binaries
# (PNG icons), asset-catalog colour JSON (generated by scripts/palette),
# Markdown/notes (README, DESIGN_SYSTEM.md, todo.md, PR template), and
# lock/editor files. Run AFTER the code freeze (with gen-pattern-map.sh).
set -euo pipefail
cd "$(dirname "$0")/.."

outdir=${1:-docs/source/generated}
mkdir -p "$outdir"

# Order (Sprint 3 plan, H.21): app code by layer, tests, resources, config,
# manifests, backend, scripts, CI.
groups=(
    "App|codey/Sources/CodeyApp.swift codey/Sources/ContentView.swift codey/Sources/App/"
    "Models|codey/Sources/Models/"
    "View models|codey/Sources/ViewModels/"
    "Services|codey/Sources/Services/"
    "Design system|codey/Sources/DesignSystem/"
    "Features|codey/Sources/Features/"
    "Navigation|codey/Sources/Navigation/"
    "Support|codey/Sources/Support/"
    "Unit tests|codey/Tests/"
    "UI tests|codey/UITests/"
    "Resources|codey/Resources/Schemas/ codey/Resources/questions-seed.json codey/Resources/starter-decks.json"
    "Build configuration|Config/Base.xcconfig Config/Secrets.example.xcconfig"
    "Project manifests|Project.swift Tuist.swift Tuist/Package.swift Tuist/Package.resolved .gitignore .mcp.json"
    "Supabase backend|supabase/migrations/ supabase/tests/ supabase/checks/"
    "Scripts|scripts/"
    "Continuous integration|.github/workflows/"
)

language_of() {
    case "$1" in
        *.swift) echo Swift ;;
        *.sql) echo CodeySQL ;;
        *.sh) echo CodeyBash ;;
        *.py) echo CodeyPython ;;
        *.json|*.resolved|.mcp.json) echo CodeyJSON ;;
        *.yml|*.yaml) echo CodeyYAML ;;
        *) echo CodeyPlain ;;
    esac
}
label_of() { printf 'appB:%s' "$(printf '%s' "$1" | sed 's/[^A-Za-z0-9]/-/g')"; }
tex_escape() { sed -e 's/[_&%#$]/\\&/g'; }
# Big seed data is set smaller so the appendix stays readable.
size_of() { case "$1" in *questions-seed.json|*starter-decks.json) echo '\scriptsize' ;; *) echo '\footnotesize' ;; esac; }

seen=$(mktemp)
trap 'rm -f "$seen"' EXIT
count=0
{
    echo "% Generated by scripts/gen-appendix-b.sh on $(git rev-parse --short HEAD). Do not edit."
    for entry in "${groups[@]}"; do
        title=${entry%%|*}
        read -r -a paths <<<"${entry#*|}"
        files=$(git ls-files -- "${paths[@]}" | grep -vE '\.(png|md)$|/Assets\.xcassets/' | sort || true)
        [[ -z "$files" ]] && continue
        printf '\\subsection*{%s}\\addcontentsline{toc}{subsection}{%s}\n' "$title" "$title"
        while IFS= read -r file; do
            grep -qxF -- "$file" "$seen" && continue
            echo "$file" >> "$seen"
            count=$((count + 1))
            printf '\\subsubsection{%s}\\label{%s}\n' "$(tex_escape <<<"$file")" "$(label_of "$file")"
            printf '\\lstinputlisting[language=%s,basicstyle=%s\\ttfamily]{../../%s}\n\n' \
                "$(language_of "$file")" "$(size_of "$file")" "$file"
        done <<<"$files"
    done
} > "$outdir/appendix_b.tex"

cat > "$outdir/appendix_b_preamble.tex" <<'TEX'
